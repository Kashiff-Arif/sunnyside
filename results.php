<script>
document.addEventListener("DOMContentLoaded", function () {

    const videoItems = document.querySelectorAll(".results-hero__video , .results-testimonials__media");
    const videoModal = document.querySelector("#videoModal");
    const modalVideo = document.querySelector("#modalVideo");
    const videoModalClose = document.querySelector(".video-modal__close");
    const videoModalOverlay = document.querySelector(".video-modal__overlay");

    if (!videoItems.length || !videoModal || !modalVideo) return;


    // Open video modal
    videoItems.forEach(function (videoItem) {

        videoItem.addEventListener("click", function () {

            const videoUrl = videoItem.getAttribute("data-video-url");

            if (!videoUrl) return;

            modalVideo.src = videoUrl;

            videoModal.classList.add("is-open");

            modalVideo.load();

            modalVideo.play().catch(function (error) {
                console.log("Autoplay blocked:", error);
            });

        });

    });


    // Close video modal
    function closeVideoModal() {

        videoModal.classList.remove("is-open");

        modalVideo.pause();
        modalVideo.currentTime = 0;

        modalVideo.removeAttribute("src");
        modalVideo.load();
    }


    // Close button
    if (videoModalClose) {
        videoModalClose.addEventListener("click", closeVideoModal);
    }


    // Close overlay
    if (videoModalOverlay) {
        videoModalOverlay.addEventListener("click", closeVideoModal);
    }


    // Close with ESC
    document.addEventListener("keydown", function (event) {

        if (event.key === "Escape" && videoModal.classList.contains("is-open")) {
            closeVideoModal();
        }

    });

});
</script>
