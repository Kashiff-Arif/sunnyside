                <h2>Frequently Asked Questions</h2> 
                <h3>What is Sunnyside?</h3>
                <p>Sunnyside is an alcohol moderation platform that helps people drink less or quit through personalized drink-tracking plans, human coaching, community support, and optional prescription naltrexone via Sunnyside Med. It was founded in 2020 (formerly Cutback Coach) and has helped over 600,000 people reduce more than 24 million drinks. Unlike abstinence-only programs, Sunnyside supports moderation as a valid goal.</p>
                <h3>How does Sunnyside work?</h3>
                <p>Users take a personalized quiz to set weekly drink-reduction goals. The app then provides daily tracking, pattern recognition, and nudges. A real human coach communicates via text or online calls to provide accountability and support. The community feature connects members with peers on similar journeys. Progress analytics show improvements in sleep, dry days, money saved, and overall consumption trends.</p>
                <h3>Does Sunnyside prescribe naltrexone?</h3>
                <p>Yes. Sunnyside Med, the medical arm of the platform, provides telehealth consultations with licensed physicians who can prescribe naltrexone for alcohol craving reduction. Naltrexone is a medication that blocks opioid receptors in the brain, reducing the rewarding effects of alcohol. Sunnyside Med integrates the prescription with the app’s coaching and tracking tools.</p>
                <h3>How much does Sunnyside cost?</h3>
                <p>Sunnyside offers three plans: a Basic plan at $8.25/month ($99/year) for tracking and community features, a Cutback Coach plan at $24.83/month ($298/year) for higher-touch human coaching, and a Sunnyside Med plan at $99/month ($297/quarter) that includes telehealth naltrexone prescriptions plus coaching. All plans include a 15-day free trial and 30-day money-back guarantee.</p>
                <h3>Is Sunnyside effective?</h3>
                <p>A clinical study demonstrated that Sunnyside reduces weekly alcohol consumption by at least 33%. Self-reported outcomes show 96.7% of members drink less, 90% reduce binge drinking, 75% drink significantly less within two weeks, and 76% report improved mental health. Sunnyside has applied for NIH funding for a first-of-its-kind clinical trial to further study its impact.</p>
                <h3>What is the difference between Sunnyside and AA?</h3>
                <p>Sunnyside and Alcoholics Anonymous (AA) take fundamentally different approaches. AA is an abstinence-based, 12-step peer support program that requires complete sobriety. Sunnyside is a moderation-focused platform that supports both cutting back and quitting, using technology (app-based tracking), human coaching, and optional medication (naltrexone). Sunnyside is designed for people who want to drink less but may not identify as having a severe alcohol use disorder or may not be ready for full abstinence.</p>
                <h3>How is Sunnyside different from other alcohol apps?</h3>
                <p>Sunnyside differentiates through its combination of behavioral tools, real human coaching, and integrated medical treatment via Sunnyside Med. Most alcohol apps focus on either tracking or community, while Sunnyside combines personalized plans, daily tracking with pattern recognition, one-on-one coaching via text or calls, peer community, and optional naltrexone prescriptions — all in a single platform. The 33% clinical reduction in weekly drinking and 600,000+ user base further distinguish it.</p>
