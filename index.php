    document.addEventListener("DOMContentLoaded", function () {

    const videoMembers = document.querySelectorAll(".member");
    const videoModal = document.querySelector("#videoModal");
    const modalVideo = document.querySelector("#modalVideo");
    const videoModalClose = document.querySelector(".video-modal__close");
    const videoModalOverlay = document.querySelector(".video-modal__overlay");


    // Open modal
    videoMembers.forEach(function (member) {

        member.addEventListener("click", function () {

            const videoUrl = member.getAttribute("data-video-url");

            if (!videoUrl) return;

            modalVideo.src = videoUrl;

            videoModal.classList.add("is-open");

            modalVideo.load();

            // Autoplay
            modalVideo.play().catch(function (error) {
                console.log("Autoplay blocked:", error);
            });

        });

    });


    // Close modal
    function closeVideoModal() {

        videoModal.classList.remove("is-open");

        // Stop video
        modalVideo.pause();

        // Reset video
        modalVideo.currentTime = 0;

        // Remove source
        modalVideo.removeAttribute("src");

        modalVideo.load();
    }


    // Close button
    videoModalClose.addEventListener("click", function () {
        closeVideoModal();
    });


    // Close overlay
    videoModalOverlay.addEventListener("click", function () {
        closeVideoModal();
    });


    // Close with ESC
    document.addEventListener("keydown", function (event) {

        if (event.key === "Escape") {
            closeVideoModal();
        }

    });

});
