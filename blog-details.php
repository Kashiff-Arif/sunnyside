                </p>
                <ul>
                    <li>
                        <b>Improved sleep.</b> Alcohol in high amounts can disrupt sleep patterns causing you to awake tired and unrested. Cutting back from high to moderate or low amounts of alcohol has been shown to improve sleep quality substantially.  
