                   Oral naltrexone does not cause the kind of unpleasant reaction to alcohol associated with medications such as disulfiram. Naltrexone has also been studied in people who continued drinking and wanted to reduce their alcohol consumption. Whether naltrexone is appropriate for you should be determined by a licensed clinician. You can learn more about how naltrexone works.
