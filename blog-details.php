                    <li>
                        <b>Anxiety reduction.</b> A decrease of 30% in drinking in 30 days (which is being achieved by Sunnyside members) can lead to better sleep and reduced anxiety. Excessive alcohol consumption causes hormonal imbalances which can increase anxiety in stressful situations. 
                    </li>
                    <li>
                        <b>Weight management.</b> Overdoing it on alcohol consumption is a common barrier to maintaining a healthy weight. At an average of 125 calories per drink, even a small reduction can make a big difference.
