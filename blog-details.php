            </h3>

            <ul>
                <li>
                    Mindful drinking means being intentional about how much you drink — not quitting. Nearly half of American adults want to reduce their alcohol intake, and this approach focuses on awareness and moderation rather than abstinence.
                </li>

                <li>
                    Even small reductions produce measurable health benefits. Cutting back improves sleep quality, lowers anxiety, supports weight loss (one fewer drink per day saves ~18,000 calories per year), and reduces blood pressure within 30 days.
                </li>

                <li>
                Tracking what you drink is the simplest way to start. Research and Sunnyside member data show that simply recording your drinks — without setting goals — changes behavior and leads to an average 29% reduction in weekly consumption.
                </li>
